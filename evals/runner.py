"""Run the scenarios against the real model and write a report and the example conversations.

Usage: python -m evals.runner [--output-dir eval-results] [--write-examples] [--only NAME ...]
"""

import argparse
import json
import re
import sys
from collections import Counter
from dataclasses import dataclass, field, replace
from datetime import date
from decimal import Decimal
from pathlib import Path

from emporio_agent.agent import ToolCall, build_agent
from emporio_agent.config import ConfigError, Settings, load_settings
from emporio_agent.prompts import build_system
from emporio_agent.text import normalize
from evals.scenarios import SCENARIOS, Scenario

EXAMPLES_DIR = Path("examples")
MONEY = re.compile(r"R\$\s?\d[\d.]*(?:,\d{2})?")


@dataclass
class Transcript:
    scenario: Scenario
    turns: list[tuple[str, str]] = field(default_factory=list)
    calls: list[list[ToolCall]] = field(default_factory=list)

    @property
    def replies(self) -> str:
        return "\n".join(reply for _, reply in self.turns)

    @property
    def tools_used(self) -> set[str]:
        return {call.name for turn in self.calls for call in turn}

    @property
    def tool_output(self) -> str:
        return "\n".join(call.result.content for turn in self.calls for call in turn)


def _money_values(text: str) -> set[Decimal]:
    values = set()
    for match in MONEY.findall(text):
        number = match.removeprefix("R$").strip().replace(".", "").replace(",", ".")
        values.add(Decimal(number))
    return values


def check(transcript: Transcript, manual: str) -> list[str]:
    """Return the failed expectations of one conversation."""
    scenario = transcript.scenario
    replies = normalize(transcript.replies)
    failures = []

    for tool in scenario.expected_tools:
        if tool not in transcript.tools_used:
            failures.append(f"expected tool not called: {tool}")
    for tool in scenario.forbidden_tools:
        if tool in transcript.tools_used:
            failures.append(f"forbidden tool called: {tool}")
    for text in scenario.must_include:
        if normalize(text) not in replies:
            failures.append(f"missing from replies: {text}")
    for text in scenario.must_not_include:
        if normalize(text) in replies:
            failures.append(f"must not appear in replies: {text}")

    # Every price the agent states must come from a tool, the manual or the customer.
    known = _money_values(f"{transcript.tool_output}\n{manual}\n{' '.join(scenario.turns)}")
    for value in sorted(_money_values(transcript.replies) - known):
        failures.append(f"price not backed by any source: {value}")
    return failures


def run_scenario(scenario: Scenario, settings: Settings) -> tuple[Transcript, Counter[str]]:
    transcript = Transcript(scenario)
    current: list[ToolCall] = []
    agent, llm = build_agent(settings, current.append)

    for message in scenario.turns:
        reply = agent.reply(message)
        transcript.turns.append((message, reply))
        transcript.calls.append(list(current))
        current.clear()
    return transcript, llm.usage


def render_markdown(transcript: Transcript, settings: Settings) -> str:
    """Format a conversation exactly as it happened. This file must never be edited by hand."""
    lines = [
        f"# {transcript.scenario.title}",
        "",
        f"> Real agent output, generated by `python -m evals.runner --write-examples` "
        f"on {date.today().isoformat()} with `{settings.model}`. "
        f"Store date: {settings.now():%Y-%m-%d %H:%M}.",
        "",
    ]
    for (message, reply), calls in zip(transcript.turns, transcript.calls, strict=True):
        lines += [f"**Cliente:** {message}", ""]
        for call in calls:
            arguments = json.dumps(call.arguments, ensure_ascii=False)
            lines += [f"> Tool: `{call.name}({arguments})`", ""]
        lines += [f"**Sol:** {reply}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the end-to-end scenarios.")
    parser.add_argument("--output-dir", type=Path, default=Path("eval-results"))
    parser.add_argument("--write-examples", action="store_true")
    parser.add_argument("--only", nargs="*", help="scenario names to run")
    args = parser.parse_args()
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")

    try:
        settings = load_settings()
    except ConfigError as error:
        print(f"Configuration error: {error}", file=sys.stderr)
        return 2

    settings = replace(settings, tickets_path=args.output_dir / "tickets.jsonl")
    manual = build_system(settings.now())[0]["text"]
    args.output_dir.mkdir(parents=True, exist_ok=True)

    selected = [s for s in SCENARIOS if not args.only or s.name in args.only]
    results = []
    usage: Counter[str] = Counter()

    for scenario in selected:
        transcript, scenario_usage = run_scenario(scenario, settings)
        usage.update(scenario_usage)
        failures = check(transcript, manual)
        results.append({"name": scenario.name, "passed": not failures, "failures": failures})
        print(f"[{'PASS' if not failures else 'FAIL'}] {scenario.name}")
        for failure in failures:
            print(f"       {failure}")

        markdown = render_markdown(transcript, settings)
        (args.output_dir / f"{scenario.name}.md").write_text(markdown, encoding="utf-8")
        if args.write_examples and scenario.example:
            EXAMPLES_DIR.mkdir(exist_ok=True)
            (EXAMPLES_DIR / f"{scenario.example}.md").write_text(markdown, encoding="utf-8")

    passed = sum(result["passed"] for result in results)
    report = {
        "model": settings.model,
        "effort": settings.effort,
        "passed": passed,
        "total": len(results),
        "usage": usage,
        "results": results,
    }
    report_path = args.output_dir / "report.json"
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\n{passed}/{len(results)} passed with {settings.model}. Usage: {dict(usage)}")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
